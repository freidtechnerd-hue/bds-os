"""Bake licensed DejaVu glyph coverage; runtime needs no TrueType interpreter."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
font=ImageFont.truetype(str(ROOT/'third_party/dejavu/DejaVuSansMono.ttf'),44)
glyphs=[]
for code in range(128):
    img=Image.new('L',(32,48));draw=ImageDraw.Draw(img)
    if code>=32:draw.text((2,-2),chr(code),font=font,fill=255)
    glyphs.append(list(img.resize((8,12),Image.Resampling.LANCZOS).getdata()))
header='/* Generated by tools/build_ui_font.py; DejaVu/Bitstream license in third_party/dejavu. */\n#ifndef BDS_UI_FONT_H\n#define BDS_UI_FONT_H\nstatic const unsigned char ui_font[128][96]={\n'
header+='\n'.join('{'+','.join(map(str,g))+'},' for g in glyphs)+'\n};\n#endif\n'
(ROOT/'kernel/ui_font.h').write_text(header,encoding='utf-8')
